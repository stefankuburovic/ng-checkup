import { formatCount, plural } from '../checks/context.js';
import type { CheckResult, Finding, Grade, Report } from '../types.js';
import { renderNotes } from './notes.js';
import { formatDuration, formatLocation, gradeLabel, kindLabel, overallScore, projectAreas, remainingCount, SCORE_EXPLANATION, severityLabel, topPriorities } from './summary.js';

/**
 * Renders the report as one self-contained HTML file.
 *
 * Self-contained is a hard requirement, not a style choice: the report is
 * meant to be mailed to a client, attached to a ticket or opened on a machine
 * without network, and it describes a private codebase. So there is no
 * external font, script, stylesheet or image, and nothing on the page phones
 * home. It follows the system light/dark preference and prints cleanly, since
 * "save as PDF" is how many readers will pass it on.
 */
export function renderHtml(report: Report): string {
  if (report.client) return renderClientHtml(report, report.client);
  const { project } = report;
  const score = overallScore(report);
  const priorities = topPriorities(report);
  const meta = [kindLabel(project.kind), project.angularVersion ? `Angular ${project.angularVersion}` : undefined, plural(project.sourceFiles, 'TypeScript file'), plural(project.templateFiles, 'template'), plural(project.linesOfCode, 'line') + ' of code', project.generatedFiles ? `${plural(project.generatedFiles, 'generated file')} left out` : undefined]
    .filter(Boolean)
    .join(' · ');

  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="generator" content="${escape(`${report.tool.name} ${report.tool.version}`)}">
<title>Angular checkup: ${escape(project.name)}</title>
<style>${STYLES}</style>
</head>
<body>
<main>
  <header class="masthead">
    <div>
      <p class="eyebrow">Angular checkup</p>
      <h1>${escape(project.name)}</h1>
      <p class="meta">${escape(meta)}</p>
      <p class="meta">Generated ${escape(report.generatedAt.slice(0, 10))}</p>
    </div>
    ${score === undefined ? '' : scoreRing(score)}
  </header>

  <section aria-labelledby="overview">
    <h2 id="overview" class="section-title">Overview</h2>
    <div class="cards">
      ${report.checks.map(overviewCard).join('\n      ')}
    </div>
  </section>

  ${
    priorities.length === 0
      ? ''
      : `<section aria-labelledby="priorities">
    <h2 id="priorities" class="section-title">Top priorities</h2>
    <ol class="priorities">
      ${priorities
        .map(
          ({ check, finding }) =>
            `<li><span class="chip sev-${finding.severity}">${severityLabel(finding.severity)}</span><span><strong>${inline(finding.message)}</strong> <a href="#${check.id}" class="area">${escape(check.title)}</a></span></li>`,
        )
        .join('\n      ')}
    </ol>
  </section>`
  }

  ${report.projects ? projectsSection(report) : ''}

  ${report.baseline ? baselineSection(report.baseline) : ''}

  ${report.migration ? migrationSection(report.migration) : ''}

  ${report.plan ? planSection(report.plan) : ''}

  ${report.checks.map(checkSection).join('\n  ')}

  <footer>
    <p>${score === undefined ? '' : `Score: ${escape(SCORE_EXPLANATION)} `}File counts are static and need no build; deprecations come from the installed packages' own <code>@deprecated</code> tags.</p>
    <p>Generated by ${escape(report.tool.name)} ${escape(report.tool.version)} in ${escape(formatDuration(report.durationMs))}.</p>
  </footer>
</main>
</body>
</html>
`;
}

/**
 * The client report (`--client`): the deliverable of a paid Health Check.
 *
 * Built for two readers. Management reads the first pages: a cover, a
 * summary in sentences, the key figures, what to act on and the roadmap,
 * then the consultant's own recommendations, estimates and price from the
 * notes file. The team reads the appendix, which is the full standard report.
 * Everything up to the notes is generated from the measurements; nothing in
 * it is an estimate, which is why the estimate column lives in the notes.
 * Prints to PDF with the cover and the appendix on pages of their own.
 */
function renderClientHtml(report: Report, client: NonNullable<Report['client']>): string {
  const { project } = report;
  const score = overallScore(report);
  const graded = report.checks.filter((check) => check.grade !== 'info');
  const count = (grade: Grade): number => graded.filter((check) => check.grade === grade).length;
  // An AngularJS app is first of all that; its summary opens the report instead of the Angular version's.
  const version = report.checks.find((check) => check.id === 'angularjs') ?? report.checks.find((check) => check.id === 'version');
  const migration = report.migration;
  const actions = report.checks
    .flatMap((check) => check.findings.filter((finding) => finding.severity === 'high' || finding.severity === 'medium').map((finding) => ({ check, finding })))
    .sort((left, right) => (left.finding.severity === right.finding.severity ? 0 : left.finding.severity === 'high' ? -1 : 1));
  const plan = report.plan;
  // The version is already the summary's first sentence; the urgent list names the rest.
  const urgent = actions.filter(({ check, finding }) => finding.severity === 'high' && check.id !== version?.id).slice(0, 3);
  // "Unit tests run…" reads as one sentence once joined; an acronym, code or a name (Angular, AngularJS) stays as it is.
  const clause = (message: string): string => message.replace(/\.$/, '').replace(/^(?!Angular)([A-Z])(?=[a-z])/, (letter) => letter.toLowerCase());
  const summary = [
    version ? version.summary : undefined,
    `Of ${plural(graded.length, 'graded area')}, ${formatCount(count('poor'))} ${count('poor') === 1 ? 'is' : 'are'} poor, ${formatCount(count('fair'))} fair and ${formatCount(count('good'))} good${score === undefined ? '' : `, for an overall score of ${score} out of 100`}.`,
    migration ? `Leaving AngularJS takes ${plural(migration.phases.length, 'phase')} with ${plural(migration.phases.reduce((sum, phase) => sum + phase.items.length, 0), 'piece')} of work, each shipping on its own.` : undefined,
    plan ? `Reaching Angular ${plan.to} takes ${plural(plan.steps.length, '`ng update` step')}, with ${plural(plan.before.length + plan.steps.reduce((sum, step) => sum + step.items.length, 0), 'piece')} of work along the way, listed below.` : undefined,
    urgent.length > 0 ? `The most urgent: ${urgent.map(({ finding }) => clause(finding.message)).join('; ')}.` : undefined,
  ].filter((sentence): sentence is string => sentence !== undefined);
  const date = report.generatedAt.slice(0, 10);
  const places = (finding: Finding): string => (finding.count !== undefined ? formatCount(finding.count) : finding.files && finding.files.length > 0 ? formatCount(finding.files.length) : '-');

  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="generator" content="${escape(`${report.tool.name} ${report.tool.version}`)}">
<title>Angular Health Check: ${escape(client.name)}</title>
<style>${STYLES}${CLIENT_STYLES}</style>
</head>
<body>
<main>
  <header class="cover">
    <p class="eyebrow">Angular Health Check</p>
    <h1>${escape(client.name)}</h1>
    <p class="cover-project">${escape(project.name)}${project.angularVersion ? ` · Angular ${escape(project.angularVersion)}` : ''}</p>
    <dl class="cover-meta">
      <div><dt>Codebase</dt><dd>${escape(report.root)}</dd></div>
      <div><dt>Date</dt><dd>${escape(date)}</dd></div>
      ${client.preparedBy ? `<div><dt>Prepared by</dt><dd>${escape(client.preparedBy)}</dd></div>` : ''}
    </dl>
    ${score === undefined ? '' : scoreRing(score)}
  </header>

  <section aria-labelledby="summary-title">
    <h2 id="summary-title" class="section-title">Summary</h2>
    <p class="lead">${summary.map(inline).join(' ')}</p>
    <dl class="metrics">
      ${[
        ['Score', score === undefined ? '-' : `${score}/100`, 'average of the graded areas'],
        ...(migration && !project.angularVersion
          ? [
              ['AngularJS', migration.from.replace(/^AngularJS ?/, '') || '-', `moving to Angular ${migration.to}`],
              ['Migration phases', formatCount(migration.phases.length), 'each shipping on its own'],
            ]
          : [
              ['Angular', project.angularVersion ?? '-', plan ? `latest is ${plan.to}` : ''],
              ['Upgrade steps', plan ? formatCount(plan.steps.length) : '-', 'one major at a time'],
            ]),
        ['To act on', formatCount(actions.length), `${formatCount(actions.filter(({ finding }) => finding.severity === 'high').length)} high priority`],
        ['Code', formatCount(project.linesOfCode), `lines in ${formatCount(project.sourceFiles)} files`],
      ]
        .map(([label, value, hint]) => `<div class="metric"><dt>${escape(label!)}</dt><dd>${escape(value!)}</dd>${hint ? `<dd class="hint">${escape(hint)}</dd>` : ''}</div>`)
        .join('\n      ')}
    </dl>
  </section>

  ${
    actions.length === 0
      ? ''
      : `<section aria-labelledby="actions-title">
    <h2 id="actions-title" class="section-title">What to act on</h2>
    <div class="table-wrap"><table class="projects actions">
      <thead><tr><th>Priority</th><th>Finding</th><th>Area</th><th class="num">Places</th></tr></thead>
      <tbody>
      ${actions.map(({ check, finding }) => `<tr><td><span class="chip sev-${finding.severity}">${severityLabel(finding.severity)}</span></td><td>${inline(finding.message)}</td><td><a href="#${check.id}">${escape(check.title)}</a></td><td class="num">${places(finding)}</td></tr>`).join('\n      ')}
      </tbody>
    </table></div>
  </section>`
  }

  ${
    migration
      ? `<section aria-labelledby="migration-roadmap-title">
    <h2 id="migration-roadmap-title" class="section-title">Roadmap: ${escape(migration.from)} → Angular ${migration.to}</h2>
    <div class="table-wrap"><table class="projects roadmap">
      <thead><tr><th>Phase</th><th>What it involves</th></tr></thead>
      <tbody>
      ${migration.phases.map((phase, index) => `<tr><td><strong>${index + 1}. ${escape(phase.title)}</strong></td><td>${phase.items.map((item) => `${inline(item.title)}${item.count !== undefined ? ` <span class="muted">(${formatCount(item.count)})</span>` : ''}`).join('<br>')}</td></tr>`).join('\n      ')}
      </tbody>
    </table></div>
    <p class="check-summary">Counts are places in the code each change touches. What each phase achieves is in the appendix.</p>
  </section>`
      : ''
  }

  ${
    plan
      ? `<section aria-labelledby="roadmap-title">
    <h2 id="roadmap-title" class="section-title">Roadmap: Angular ${plan.from} → ${plan.to}</h2>
    <div class="table-wrap"><table class="projects roadmap">
      <thead><tr><th>Step</th><th>What it involves</th><th>Toolchain</th></tr></thead>
      <tbody>
      ${plan.before.length > 0 ? `<tr><td><strong>First</strong></td><td>${plan.before.map((item) => `${inline(item.title)}${item.count !== undefined ? ` <span class="muted">(${formatCount(item.count)})</span>` : ''}`).join('<br>')}</td><td></td></tr>` : ''}
      ${plan.steps
        .map(
          (step) =>
            `<tr><td><strong>Angular ${step.to}</strong></td><td>${step.items.length === 0 ? '<span class="muted">The update itself</span>' : step.items.map((item) => `${inline(item.title)}${item.count !== undefined ? ` <span class="muted">(${formatCount(item.count)})</span>` : ''}`).join('<br>')}</td><td>${step.requirements.filter((requirement) => requirement.satisfied === false).map((requirement) => `${escape(requirement.name)} ${escape(requirement.range)}`).join('<br>') || '<span class="muted">no change</span>'}</td></tr>`,
        )
        .join('\n      ')}
      </tbody>
    </table></div>
    <p class="check-summary">Counts are places in the code each change touches. Commands and details per step are in the appendix.</p>
  </section>`
      : ''
  }

  ${client.notes ? `<section class="notes" aria-labelledby="notes-title">\n    <h2 id="notes-title" class="section-title">Recommendations${client.preparedBy ? ` by ${escape(client.preparedBy.split(',')[0]!.trim())}` : ''}</h2>\n    ${renderNotes(client.notes)}\n  </section>` : ''}

  <div class="appendix">
    <h2 class="appendix-title">Appendix: area by area</h2>
    <div class="cards">
      ${report.checks.map(overviewCard).join('\n      ')}
    </div>
    ${report.projects ? projectsSection(report) : ''}
    ${report.migration ? migrationSection(report.migration) : ''}
    ${plan ? planSection(plan) : ''}
    ${report.checks.map(checkSection).join('\n  ')}
  </div>

  <footer>
    <p>${score === undefined ? '' : `Score: ${escape(SCORE_EXPLANATION)} `}Measured by static analysis of the source, without building or running it and without the code leaving the machine. Deprecations come from the Angular packages' own <code>@deprecated</code> tags for the versions in use.</p>
    <p>Generated with ${escape(report.tool.name)} ${escape(report.tool.version)} on ${escape(date)}.</p>
  </footer>
</main>
</body>
</html>
`;
}

/** The score as a ring: the arc length is the score, the colour its band. */
function scoreRing(score: number): string {
  const radius = 42;
  const circumference = 2 * Math.PI * radius;
  const band: Grade = score >= 80 ? 'good' : score >= 50 ? 'fair' : 'poor';
  return `<figure class="score" aria-label="Score ${score} out of 100">
      <svg viewBox="0 0 100 100" width="112" height="112" aria-hidden="true">
        <circle cx="50" cy="50" r="${radius}" class="ring-track"/>
        <circle cx="50" cy="50" r="${radius}" class="ring-value grade-${band}" stroke-dasharray="${((score / 100) * circumference).toFixed(1)} ${circumference.toFixed(1)}" transform="rotate(-90 50 50)"/>
      </svg>
      <figcaption><span class="score-value">${score}</span><span class="score-unit">/100</span></figcaption>
    </figure>`;
}

/** The AngularJS migration plan: one card per phase, with its goal and its work in this codebase. */
function migrationSection(migration: NonNullable<Report['migration']>): string {
  const item = (entry: { title: string; command?: string; detail?: string; count?: number }): string =>
    `<li><strong>${inline(entry.title)}</strong>${entry.count !== undefined ? ` <span class="count">${formatCount(entry.count)}</span>` : ''}${entry.command ? `<code class="command">${escape(entry.command)}</code>` : ''}${entry.detail ? `<p>${inline(entry.detail)}</p>` : ''}</li>`;
  return `<section aria-labelledby="migration-title">
    <h2 id="migration-title" class="section-title">Migration plan: ${escape(migration.from)} → Angular ${migration.to}</h2>
    <p class="check-summary">${plural(migration.phases.length, 'phase')}, each shipping on its own, in the order of the Angular upgrade guide: prepare on AngularJS, run both frameworks side by side, move the code bottom up, remove AngularJS.</p>
    <ol class="steps">
      ${migration.phases
        .map(
          (phase, index) => `<li class="finding step">
        <div class="finding-head"><span class="chip sev-low">${index + 1}</span><strong>${escape(phase.title)}</strong></div>
        <p class="requirements">${inline(phase.goal)}</p>
        <ul class="plan-items">${phase.items.map(item).join('')}</ul>
      </li>`,
        )
        .join('\n      ')}
    </ol>
  </section>`;
}

/** The upgrade plan: what to settle first, then one card per major. */
function planSection(plan: NonNullable<Report['plan']>): string {
  const item = (entry: { title: string; command?: string; detail?: string; count?: number }): string =>
    `<li><strong>${inline(entry.title)}</strong>${entry.count !== undefined ? ` <span class="count">${formatCount(entry.count)}</span>` : ''}${entry.command ? `<code class="command">${escape(entry.command)}</code>` : ''}${entry.detail ? `<p>${inline(entry.detail)}</p>` : ''}</li>`;
  return `<section aria-labelledby="plan-title">
    <h2 id="plan-title" class="section-title">Upgrade plan: Angular ${plan.from} → ${plan.to}</h2>
    <p class="check-summary">${plural(plan.steps.length, 'step')}, one major at a time, as <code>ng update</code> requires. Requirements come from each version's published package metadata.</p>
    ${plan.before.length > 0 ? `<div class="finding step before"><div class="finding-head"><span class="chip sev-medium">First</span><strong>Before you start</strong></div><ul class="plan-items">${plan.before.map(item).join('')}</ul></div>` : ''}
    <ol class="steps">
      ${plan.steps
        .map(
          (step) => `<li class="finding step">
        <div class="finding-head"><span class="chip sev-low">→ ${step.to}</span><strong>Angular ${escape(step.version)}</strong></div>
        <code class="command">${escape(step.command)}</code>
        <p class="requirements">${step.requirements.map((requirement) => `<span class="${requirement.satisfied === false ? 'req req-move' : 'req'}">${escape(requirement.name)} ${escape(requirement.range)}${requirement.satisfied === false ? ` (now ${escape(requirement.current ?? '')})` : ''}</span>`).join('')}</p>
        ${step.items.length > 0 ? `<ul class="plan-items">${step.items.map(item).join('')}</ul>` : ''}
      </li>`,
        )
        .join('\n      ')}
    </ol>
  </section>`;
}

/** The per-project table of a monorepo, worst score first, with a pill per poor or fair area. */
function projectsSection(report: Report): string {
  const rows = report.projects ?? [];
  const pills = (titles: string[], grade: Grade): string => titles.map((title) => `<span class="pill grade-${grade}">${escape(title)}</span>`).join(' ');
  return `<section aria-labelledby="projects-title">
    <h2 id="projects-title" class="section-title">Projects</h2>
    <p class="check-summary">${plural(rows.length, 'project')}, worst first. Each is graded on its own code; the Angular version and the third-party packages are shared and graded below.</p>
    <div class="table-wrap"><table class="projects">
      <thead><tr><th>Project</th><th>Type</th><th class="num">Score</th><th class="num">Files</th><th class="num">High</th><th>Areas to work on</th></tr></thead>
      <tbody>
      ${rows
        .map((row) => {
          const { poor, fair } = projectAreas(row, report);
          const band: Grade = row.score === undefined ? 'info' : row.score >= 80 ? 'good' : row.score >= 50 ? 'fair' : 'poor';
          return `<tr><td><strong>${escape(row.name)}</strong><br><code>${escape(row.root || '.')}</code></td><td>${escape(row.type)}</td><td class="num"><span class="pill grade-${band}">${row.score ?? '-'}</span></td><td class="num">${formatCount(row.sourceFiles)}</td><td class="num">${row.highFindings}</td><td>${pills(poor, 'poor')} ${pills(fair, 'fair')}</td></tr>`;
        })
        .join('\n      ')}
      </tbody>
    </table></div>
  </section>`;
}

/** The comparison with the baseline: what got worse first, then what got better. */
function baselineSection(comparison: NonNullable<Report['baseline']>): string {
  const rows = [
    ...comparison.regressions.map((delta) => ({ delta, kind: 'worse' as const })),
    ...comparison.improvements.map((delta) => ({ delta, kind: 'better' as const })),
  ];
  const summary =
    rows.length === 0
      ? 'No change since the baseline.'
      : `${comparison.regressions.length} worse, ${comparison.improvements.length} better than the baseline.`;
  return `<section aria-labelledby="baseline-title">
    <h2 id="baseline-title" class="section-title">Compared with the baseline</h2>
    <p class="check-summary">${escape(summary)}</p>
    ${
      rows.length === 0
        ? ''
        : `<ul class="findings">
      ${rows
        .map(
          ({ delta, kind }) =>
            `<li class="finding"><div class="finding-head"><span class="chip ${kind === 'worse' ? 'sev-high' : 'sev-good'}">${kind === 'worse' ? 'Worse' : 'Better'}</span><strong>${escape(delta.label)}: ${delta.before} → ${delta.after}</strong></div><p>${escape(delta.check)}</p></li>`,
        )
        .join('\n      ')}
    </ul>`
    }
  </section>`;
}

/** One card of the overview grid, linking to its section. */
function overviewCard(check: CheckResult): string {
  return `<a class="card" href="#${check.id}"><span class="pill grade-${check.grade}">${gradeLabel(check.grade)}</span><strong>${escape(check.title)}</strong><span class="card-summary">${inline(check.summary)}</span></a>`;
}

/** The full section of one check: summary, metric grid, findings. */
function checkSection(check: CheckResult): string {
  return `<section class="check" id="${check.id}" aria-labelledby="${check.id}-title">
    <div class="check-head">
      <h2 id="${check.id}-title">${escape(check.title)}</h2>
      <span class="pill grade-${check.grade}">${gradeLabel(check.grade)}</span>
    </div>
    <p class="check-summary">${inline(check.summary)}</p>
    ${
      check.metrics.length === 0
        ? ''
        : `<dl class="metrics">
      ${check.metrics.map((metric) => `<div class="metric"><dt>${escape(metric.label)}</dt><dd>${escape(String(metric.value))}</dd>${metric.hint ? `<dd class="hint">${escape(metric.hint)}</dd>` : ''}</div>`).join('\n      ')}
    </dl>`
    }
    ${check.findings.length === 0 ? '' : `<ul class="findings">\n      ${check.findings.map(findingItem).join('\n      ')}\n    </ul>`}
  </section>`;
}

/** One finding with its detail and example files. */
function findingItem(finding: Finding): string {
  const more = remainingCount(finding);
  const files = finding.files ?? [];
  return `<li class="finding">
        <div class="finding-head"><span class="chip sev-${finding.severity}">${severityLabel(finding.severity)}</span><strong>${inline(finding.message)}</strong></div>
        ${finding.detail ? `<p>${inline(finding.detail)}</p>` : ''}
        ${files.length === 0 ? '' : `<ul class="files">${files.map((file) => `<li>${escape(formatLocation(file))}</li>`).join('')}${more > 0 ? `<li class="more">and ${formatCount(more)} more</li>` : ''}</ul>`}
      </li>`;
}

/** Escapes text and turns backtick spans into `<code>`, the only markup finding text uses. */
function inline(text: string): string {
  return escape(text).replace(/`([^`]+)`/g, '<code>$1</code>');
}

/** HTML-escapes text for element content and double-quoted attributes. */
export function escape(text: string): string {
  return text.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;').replace(/'/g, '&#39;');
}

