import { formatCount, plural } from '../checks/context.js';
import type { CheckResult, Finding, Grade, Report } from '../types.js';
import { formatDuration, formatLocation, gradeLabel, kindLabel, overallScore, remainingCount, SCORE_EXPLANATION, severityLabel, topPriorities } from './summary.js';

/**
 * Renders the report as one self-contained HTML file.
 *
 * Self-contained is a hard requirement, not a style choice: the report is
 * meant to be mailed to a client, attached to a ticket or opened on a machine
 * without network, and it describes a private codebase. So there is no
 * external font, script, stylesheet or image, and nothing on the page phones
 * home. It follows the system light/dark preference and prints cleanly, since
 * "save as PDF" is how many readers will pass it on.
 */
export function renderHtml(report: Report): string {
  const { project } = report;
  const score = overallScore(report);
  const priorities = topPriorities(report);
  const meta = [kindLabel(project.kind), project.angularVersion ? `Angular ${project.angularVersion}` : undefined, plural(project.sourceFiles, 'TypeScript file'), plural(project.templateFiles, 'template'), plural(project.linesOfCode, 'line') + ' of code']
    .filter(Boolean)
    .join(' · ');

  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="generator" content="${escape(`${report.tool.name} ${report.tool.version}`)}">
<title>Angular checkup: ${escape(project.name)}</title>
<style>${STYLES}</style>
</head>
<body>
<main>
  <header class="masthead">
    <div>
      <p class="eyebrow">Angular checkup</p>
      <h1>${escape(project.name)}</h1>
      <p class="meta">${escape(meta)}</p>
      <p class="meta">Generated ${escape(report.generatedAt.slice(0, 10))}</p>
    </div>
    ${score === undefined ? '' : scoreRing(score)}
  </header>

  <section aria-labelledby="overview">
    <h2 id="overview" class="section-title">Overview</h2>
    <div class="cards">
      ${report.checks.map(overviewCard).join('\n      ')}
    </div>
  </section>

  ${
    priorities.length === 0
      ? ''
      : `<section aria-labelledby="priorities">
    <h2 id="priorities" class="section-title">Top priorities</h2>
    <ol class="priorities">
      ${priorities
        .map(
          ({ check, finding }) =>
            `<li><span class="chip sev-${finding.severity}">${severityLabel(finding.severity)}</span><span><strong>${inline(finding.message)}</strong> <a href="#${check.id}" class="area">${escape(check.title)}</a></span></li>`,
        )
        .join('\n      ')}
    </ol>
  </section>`
  }

  ${report.checks.map(checkSection).join('\n  ')}

  <footer>
    <p>${score === undefined ? '' : `Score: ${escape(SCORE_EXPLANATION)} `}File counts are static and need no build; deprecations come from the installed packages' own <code>@deprecated</code> tags.</p>
    <p>Generated by ${escape(report.tool.name)} ${escape(report.tool.version)} in ${escape(formatDuration(report.durationMs))}.</p>
  </footer>
</main>
</body>
</html>
`;
}

/** The score as a ring: the arc length is the score, the colour its band. */
function scoreRing(score: number): string {
  const radius = 42;
  const circumference = 2 * Math.PI * radius;
  const band: Grade = score >= 80 ? 'good' : score >= 50 ? 'fair' : 'poor';
  return `<figure class="score" aria-label="Score ${score} out of 100">
      <svg viewBox="0 0 100 100" width="112" height="112" aria-hidden="true">
        <circle cx="50" cy="50" r="${radius}" class="ring-track"/>
        <circle cx="50" cy="50" r="${radius}" class="ring-value grade-${band}" stroke-dasharray="${((score / 100) * circumference).toFixed(1)} ${circumference.toFixed(1)}" transform="rotate(-90 50 50)"/>
      </svg>
      <figcaption><span class="score-value">${score}</span><span class="score-unit">/100</span></figcaption>
    </figure>`;
}

/** One card of the overview grid, linking to its section. */
function overviewCard(check: CheckResult): string {
  return `<a class="card" href="#${check.id}"><span class="pill grade-${check.grade}">${gradeLabel(check.grade)}</span><strong>${escape(check.title)}</strong><span class="card-summary">${inline(check.summary)}</span></a>`;
}

/** The full section of one check: summary, metric grid, findings. */
function checkSection(check: CheckResult): string {
  return `<section class="check" id="${check.id}" aria-labelledby="${check.id}-title">
    <div class="check-head">
      <h2 id="${check.id}-title">${escape(check.title)}</h2>
      <span class="pill grade-${check.grade}">${gradeLabel(check.grade)}</span>
    </div>
    <p class="check-summary">${inline(check.summary)}</p>
    ${
      check.metrics.length === 0
        ? ''
        : `<dl class="metrics">
      ${check.metrics.map((metric) => `<div class="metric"><dt>${escape(metric.label)}</dt><dd>${escape(String(metric.value))}</dd>${metric.hint ? `<dd class="hint">${escape(metric.hint)}</dd>` : ''}</div>`).join('\n      ')}
    </dl>`
    }
    ${check.findings.length === 0 ? '' : `<ul class="findings">\n      ${check.findings.map(findingItem).join('\n      ')}\n    </ul>`}
  </section>`;
}

/** One finding with its detail and example files. */
function findingItem(finding: Finding): string {
  const more = remainingCount(finding);
  const files = finding.files ?? [];
  return `<li class="finding">
        <div class="finding-head"><span class="chip sev-${finding.severity}">${severityLabel(finding.severity)}</span><strong>${inline(finding.message)}</strong></div>
        ${finding.detail ? `<p>${inline(finding.detail)}</p>` : ''}
        ${files.length === 0 ? '' : `<ul class="files">${files.map((file) => `<li>${escape(formatLocation(file))}</li>`).join('')}${more > 0 ? `<li class="more">and ${formatCount(more)} more</li>` : ''}</ul>`}
      </li>`;
}

/** Escapes text and turns backtick spans into `<code>`, the only markup finding text uses. */
function inline(text: string): string {
  return escape(text).replace(/`([^`]+)`/g, '<code>$1</code>');
}

/** HTML-escapes text for element content and double-quoted attributes. */
export function escape(text: string): string {
  return text.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;').replace(/'/g, '&#39;');
}

