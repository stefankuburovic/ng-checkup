import { formatCount, plural } from '../checks/context.js';
import type { Grade, Report } from '../types.js';
import { gradeLabel, overallScore, severityLabel, topPriorities } from './summary.js';

/**
 * The first line of every comment ng-checkup writes. The GitHub Action finds
 * its earlier comment on a pull request by this marker and edits it, so a PR
 * keeps one up-to-date comment instead of one more per push.
 */
export const COMMENT_MARKER = '<!-- ng-checkup -->';

/** A coloured dot per grade, so the table can be scanned without reading it. */
const DOTS: Record<Grade, string> = { good: '🟢', fair: '🟡', poor: '🔴', info: '⚪' };

/**
 * The report as a pull-request comment (`--report x.comment.md`).
 *
 * Shorter than the Markdown report on purpose: a reviewer reads it in the
 * diff view, between other comments. What changed comes first, because that
 * is what a pull request is about: with a baseline, the measures that got
 * worse and better than it. Then one line per area, then the top priorities
 * folded away. The full report belongs in the workflow's artifacts, which
 * the footer points to.
 */
export function renderComment(report: Report): string {
  const { project } = report;
  const score = overallScore(report);
  const comparison = report.baseline;
  const lines: string[] = [COMMENT_MARKER];

  const worse = comparison?.regressions.length ?? 0;
  const status = comparison ? (worse > 0 ? ` · ${plural(worse, 'measure')} worse than the baseline` : ' · nothing worse than the baseline') : '';
  lines.push(`### Angular checkup${score === undefined ? '' : `: ${score}/100`}${status}`, '');
  lines.push(
    `\`${project.name}\`${project.angularVersion ? ` · Angular ${project.angularVersion}` : ''} · ${plural(project.linesOfCode, 'line')} of application code · ${report.tool.name} ${report.tool.version}`,
    '',
  );

  if (comparison && (comparison.regressions.length > 0 || comparison.improvements.length > 0)) {
    lines.push('| | Measure | Baseline | Now |', '| --- | --- | ---: | ---: |');
    for (const delta of comparison.regressions) lines.push(`| **Worse** | ${cell(delta.label)} | ${formatCount(delta.before)} | **${formatCount(delta.after)}** |`);
    for (const delta of comparison.improvements) lines.push(`| Better | ${cell(delta.label)} | ${formatCount(delta.before)} | ${formatCount(delta.after)} |`);
    lines.push('');
    if (worse === 0) lines.push('Lock the improvements in with `npx ng-checkup baseline` and commit the file.', '');
  }

  lines.push('| Area | Grade | |', '| --- | --- | --- |');
  // An area that was not measured gets two words, not the full explanation: it is noise in a review.
  for (const check of report.checks) lines.push(`| ${cell(check.title)} | ${DOTS[check.grade]} ${gradeLabel(check.grade)} | ${check.grade === 'info' ? '_not measured_' : cell(check.summary)} |`);
  lines.push('');

  const priorities = topPriorities(report);
  if (priorities.length > 0) {
    lines.push('<details><summary>Top priorities</summary>', '');
    priorities.forEach(({ check, finding }, index) => lines.push(`${index + 1}. **${severityLabel(finding.severity)}:** ${finding.message} _(${check.title})_`));
    lines.push('', '</details>', '');
  }

  lines.push(`<sub>The full report is in the CI artifacts. Generated by [ng-checkup](https://github.com/stefankuburovic/ng-checkup).</sub>`, '');
  return lines.join('\n');
}

/** A table cell: no pipe that would split it, no line break that would end the row. */
function cell(text: string): string {
  return text.replace(/\|/g, '\\|').replace(/\n/g, ' ');
}
