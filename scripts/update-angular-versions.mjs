#!/usr/bin/env node
/**
 * Regenerates src/angular-versions.ts from the npm registry: for every Angular
 * major, the last released version and what it requires (Node.js from
 * @angular/core's engines, TypeScript from @angular/compiler-cli's peer
 * dependency, RxJS and zone.js from @angular/core's peer dependencies).
 *
 * The upgrade plan reads this snapshot instead of the registry so it works
 * offline and is reproducible. Run it before each release:
 *
 *   node scripts/update-angular-versions.mjs
 *
 * It uses the registry's `vN-lts` dist-tags (the last release of each major)
 * and `latest` for the newest one.
 */
import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

/** `npm view <spec> <field> --json`, parsed; undefined when the field is absent. */
function view(spec, field) {
  try {
    const output = execFileSync('npm', ['view', spec, field, '--json'], { encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }).trim();
    return output ? JSON.parse(output) : undefined;
  } catch {
    return undefined;
  }
}

const tags = view('@angular/core', 'dist-tags');
const latestMajor = Number(String(tags.latest).split('.')[0]);
const entries = [];
for (let major = 4; major <= latestMajor; major++) {
  const tag = major === latestMajor ? 'latest' : `v${major}-lts`;
  if (!(tag in tags)) continue;
  const version = tags[tag];
  const core = `@angular/core@${version}`;
  const peers = view(core, 'peerDependencies') ?? {};
  entries.push({
    major,
    version,
    node: view(core, 'engines.node') ?? null,
    typescript: view(`@angular/compiler-cli@${version}`, 'peerDependencies.typescript') ?? null,
    rxjs: peers.rxjs ?? null,
    zoneJs: peers['zone.js'] ?? null,
  });
  process.stderr.write(`${major}: ${version}\n`);
}

const target = fileURLToPath(new URL('../src/angular-versions.ts', import.meta.url));
writeFileSync(
  target,
  `// Generated by scripts/update-angular-versions.mjs on ${new Date().toISOString().slice(0, 10)}. Do not edit by hand.

/** What one Angular major requires, from the npm registry. A null field was not published for that major. */
export interface AngularVersionInfo {
  major: number;
  /** The last released version of the major when the snapshot was taken. */
  version: string;
  /** Node.js range from @angular/core's \`engines\`. */
  node: string | null;
  /** TypeScript range from @angular/compiler-cli's peer dependency. */
  typescript: string | null;
  rxjs: string | null;
  zoneJs: string | null;
}

/** Every Angular major from 4 to the newest, oldest first. */
export const ANGULAR_VERSIONS: AngularVersionInfo[] = ${JSON.stringify(entries, null, 2)};
`,
);
process.stderr.write(`wrote ${target}\n`);
